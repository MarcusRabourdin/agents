"""Dump the FastAPI schema into doc/swagger.yaml.

Keeps the committed contract from drifting away from the code.

    python backend/scripts/export_swagger.py            # write the file
    python backend/scripts/export_swagger.py --check     # fail if out of date

`--check` is what CI should run: it exits 1 and prints a diff when an endpoint
was added or changed without regenerating the spec.
"""

import argparse
import difflib
import sys
from pathlib import Path

import yaml

BACKEND_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = BACKEND_ROOT.parent
SPEC_PATH = REPO_ROOT / "doc" / "swagger.yaml"

sys.path.insert(0, str(BACKEND_ROOT))

from app.main import app  # noqa: E402  (needs BACKEND_ROOT on sys.path first)

HEADER = (
    "# Generated by backend/scripts/export_swagger.py - do not edit by hand.\n"
    "# Change the FastAPI route or model, then regenerate.\n"
)


def render_spec() -> str:
    schema = app.openapi()
    body = yaml.safe_dump(schema, sort_keys=False, allow_unicode=True, width=100)
    return HEADER + body


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write, exit 1 if the committed spec is stale",
    )
    args = parser.parse_args()

    generated = render_spec()
    current = SPEC_PATH.read_text() if SPEC_PATH.exists() else ""

    if args.check:
        if generated == current:
            print(f"{SPEC_PATH.relative_to(REPO_ROOT)} is up to date")
            return 0
        diff = difflib.unified_diff(
            current.splitlines(keepends=True),
            generated.splitlines(keepends=True),
            fromfile="committed",
            tofile="generated",
        )
        sys.stdout.writelines(diff)
        print(f"\n{SPEC_PATH.relative_to(REPO_ROOT)} is stale, regenerate it")
        return 1

    SPEC_PATH.parent.mkdir(parents=True, exist_ok=True)
    SPEC_PATH.write_text(generated)
    paths = len(app.openapi()["paths"])
    print(f"wrote {SPEC_PATH.relative_to(REPO_ROOT)} ({paths} paths)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
